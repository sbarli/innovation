#!/usr/bin/env node
/**
 * Generates supabase/seeds/seed.cards.sql from docs/innovation_db.cards.json.
 *
 * Reads the 105-card MongoDB export, strips _id and __v fields,
 * maps camelCase fields to snake_case column names, and writes
 * INSERT statements with ON CONFLICT (card_id) DO NOTHING.
 *
 * Usage (run from repo root):
 *   node packages/db/scripts/generate-cards-seed.mjs
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const packageRoot = join(__dirname, '..');
const repoRoot = join(packageRoot, '../..');
const inputPath = join(repoRoot, 'docs', 'innovation_db.cards.json');
const outputPath = join(packageRoot, 'supabase', 'seeds', 'seed.cards.sql');

const cards = JSON.parse(readFileSync(inputPath, 'utf8'));

function escapeStr(str) {
  return String(str).replace(/'/g, "''");
}

function toSqlLiteral(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'string') return `'${escapeStr(value)}'`;
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  return `'${escapeStr(JSON.stringify(value))}'::jsonb`;
}

const rows = cards.map((card) => {
  const cardId = toSqlLiteral(card.cardId);
  const name = toSqlLiteral(card.name);
  const age = toSqlLiteral(card.age);
  const color = toSqlLiteral(card.color);
  const dogmaResource = toSqlLiteral(card.dogmaResource);
  const resourceTotals = toSqlLiteral(card.resourceTotals);
  const resourceSpaces = toSqlLiteral(card.resourceSpaces);
  const dogmaEffects = toSqlLiteral(card.dogmaEffects);

  return `  (${cardId}, ${name}, ${age}, ${color}, ${dogmaResource}, ${resourceTotals}, ${resourceSpaces}, ${dogmaEffects})`;
});

const sql = `-- Card data seed — 105 Innovation cards.
-- Auto-generated by: node packages/db/scripts/generate-cards-seed.mjs
-- Do not edit manually — re-run the script if card data changes.

INSERT INTO public.cards (card_id, name, age, color, dogma_resource, resource_totals, resource_spaces, dogma_effects)
VALUES
${rows.join(',\n')}
ON CONFLICT (card_id) DO NOTHING;
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, sql, 'utf8');
console.log(`Wrote ${cards.length} cards to ${outputPath}`);
