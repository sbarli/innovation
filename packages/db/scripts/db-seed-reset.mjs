#!/usr/bin/env node
/**
 * Interactive optional seed picker + supabase db reset for @inno/db.
 *
 * - seed.core.sql and seed.cards.sql always run (see supabase/config.toml sql_paths).
 * - Other *.sql files in supabase/seeds/ are optional; this script concatenates
 *   selected ones into seeds/seed.generated.sql (gitignored), then runs reset.
 *
 * Usage:
 *   node ./scripts/db-seed-reset.mjs
 *   node ./scripts/db-seed-reset.mjs --empty-generated [-- ...supabase db reset flags]
 *
 * --empty-generated  Skip prompts; write a minimal stub seed.generated.sql, then db reset.
 */

import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { stdin as input, stdout as output } from 'node:process';
import readline from 'node:readline';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const packageRoot = join(__dirname, '..');
const seedsDir = join(packageRoot, 'supabase', 'seeds');
const generatedPath = join(seedsDir, 'seed.generated.sql');

const RESERVED = new Set(['seed.core.sql', 'seed.cards.sql', 'seed.generated.sql']);
const FLAG_EMPTY = '--empty-generated';

function listOptionalSeedFiles() {
  if (!existsSync(seedsDir)) return [];
  return readdirSync(seedsDir)
    .filter((name) => name.endsWith('.sql') && !RESERVED.has(name))
    .sort();
}

function minimalStubSql() {
  return `-- Optional seed modules (gitignored; generated by scripts/db-seed-reset.mjs)
-- No optional seed files selected.
SELECT 1 WHERE false;
`;
}

function buildGeneratedFromFiles(filenames) {
  if (filenames.length === 0) return minimalStubSql();
  const chunks = ['-- Optional seed modules (gitignored; generated by scripts/db-seed-reset.mjs)\n'];
  for (const name of filenames) {
    const abs = join(seedsDir, name);
    chunks.push(`\n-- >>> BEGIN optional seed: ${name}\n`);
    chunks.push(readFileSync(abs, 'utf8'));
    chunks.push(`\n-- <<< END optional seed: ${name}\n`);
  }
  return chunks.join('');
}

function writeGenerated(content) {
  mkdirSync(seedsDir, { recursive: true });
  writeFileSync(generatedPath, content, 'utf8');
}

function parseArgs(argv) {
  const emptyGenerated = argv.includes(FLAG_EMPTY);
  const supabaseArgs = argv.filter((a) => a !== FLAG_EMPTY);
  return { emptyGenerated, supabaseArgs };
}

function bulletSelected(on) {
  return on ? '\x1b[32m●\x1b[0m' : '\x1b[1;97m○\x1b[0m';
}

function hideCursor() { output.write('\x1b[?25l'); }
function showCursor() { output.write('\x1b[?25h'); }

function promptSelections(optionalFiles) {
  if (optionalFiles.length === 0) {
    output.write('No optional seed files in supabase/seeds/.\n');
    return Promise.resolve([]);
  }

  if (!input.isTTY) {
    output.write('Optional seeds: stdin is not a TTY; skipping interactive picker (no optional files selected).\n');
    return Promise.resolve([]);
  }

  const selectionOrder = [];
  const selected = new Set();
  let highlight = 0;

  function render() {
    const lines = [
      '\x1b[2J\x1b[H',
      'Optional seed modules (\x1b[1mseed.core.sql\x1b[0m and \x1b[1mseed.cards.sql\x1b[0m always run)',
      '\x1b[2m↑ / ↓  navigate   ·   Space  toggle   ·   Enter  confirm\x1b[0m',
      '',
    ];
    optionalFiles.forEach((name, i) => {
      const bul = bulletSelected(selected.has(i));
      const isHi = i === highlight;
      const prefix = isHi ? ' \x1b[1m›\x1b[0m ' : '   ';
      const label = isHi ? `\x1b[1m${name}\x1b[0m` : name;
      lines.push(`${prefix}${bul}  ${label}`);
    });
    lines.push('');
    output.write(lines.join('\n'));
  }

  return new Promise((resolve) => {
    readline.emitKeypressEvents(input);
    input.setRawMode(true);
    hideCursor();

    const cleanup = () => {
      input.setRawMode(false);
      input.removeListener('keypress', onKeypress);
      showCursor();
      output.write('\x1b[2J\x1b[H');
    };

    const finish = () => {
      cleanup();
      resolve(selectionOrder.map((i) => optionalFiles[i]));
    };

    const onKeypress = (str, key) => {
      if (key.ctrl && key.name === 'c') { cleanup(); process.exit(130); }
      if (key.name === 'return' || key.name === 'enter') { finish(); return; }
      const isSpace = key.name === 'space' || (str === ' ' && !key.ctrl && !key.meta);
      if (isSpace) {
        if (selected.has(highlight)) {
          selected.delete(highlight);
          const pos = selectionOrder.indexOf(highlight);
          if (pos !== -1) selectionOrder.splice(pos, 1);
        } else {
          selected.add(highlight);
          selectionOrder.push(highlight);
        }
        render();
        return;
      }
      if (key.name === 'up') { highlight = Math.max(0, highlight - 1); render(); return; }
      if (key.name === 'down') { highlight = Math.min(optionalFiles.length - 1, highlight + 1); render(); }
    };

    input.resume();
    input.on('keypress', onKeypress);
    render();
  });
}

function isLocalSupabaseRunning() {
  const r = spawnSync('pnpm', ['exec', 'supabase', 'status'], {
    cwd: packageRoot,
    stdio: ['ignore', 'pipe', 'pipe'],
    encoding: 'utf8',
    env: process.env,
  });
  return r.status === 0;
}

function promptYesNo(question) {
  return new Promise((resolve) => {
    const rl = readline.createInterface({ input, output });
    rl.question(question, (answer) => { rl.close(); resolve(/^y(es)?$/i.test(String(answer).trim())); });
  });
}

async function ensureSupabaseRunning() {
  if (isLocalSupabaseRunning()) return;

  const question =
    '\nSupabase local stack does not appear to be running (or `supabase status` failed).\n' +
    'Run `pnpm exec supabase start` now? [y/N] ';

  if (!input.isTTY) {
    output.write(`${question}\n(stdin is not a TTY — run \`pnpm exec supabase start\` from packages/db, then retry.)\n`);
    process.exit(1);
  }

  const yes = await promptYesNo(question);
  if (!yes) {
    output.write('Skipping start. Run `pnpm exec supabase start` when ready, then re-run this script.\n');
    process.exit(0);
  }

  output.write('\nRunning `pnpm exec supabase start`…\n\n');
  const start = spawnSync('pnpm', ['exec', 'supabase', 'start'], {
    cwd: packageRoot,
    stdio: 'inherit',
    env: process.env,
  });
  if (start.status !== 0) {
    output.write('\n`supabase start` exited with an error. Fix the issue above and try again.\n');
    process.exit(start.status ?? 1);
  }
  output.write('\n');
}

function runDbReset(supabaseArgs) {
  const result = spawnSync('pnpm', ['exec', 'supabase', 'db', 'reset', ...supabaseArgs], {
    cwd: packageRoot,
    stdio: 'inherit',
    env: process.env,
  });
  if (result.error) throw result.error;
  process.exit(result.status ?? 1);
}

const argv = process.argv.slice(2);
const { emptyGenerated, supabaseArgs } = parseArgs(argv);

mkdirSync(seedsDir, { recursive: true });

const optionalFiles = listOptionalSeedFiles();

if (emptyGenerated) {
  writeGenerated(minimalStubSql());
  output.write(`Wrote stub ${generatedPath} (--empty-generated).\n`);
} else {
  const chosen = await promptSelections(optionalFiles);
  const content = buildGeneratedFromFiles(chosen);
  writeGenerated(content);
  output.write(`\nWrote ${generatedPath} (${chosen.length} optional file(s): ${chosen.join(', ') || 'none'}).\n`);
}

await ensureSupabaseRunning();
runDbReset(supabaseArgs);
